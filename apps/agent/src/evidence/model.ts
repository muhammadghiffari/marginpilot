import { z } from 'zod';

const Hash = z.string().regex(/^0x[0-9a-fA-F]{64}$/);
const Address = z.string().regex(/^0x[0-9a-fA-F]{40}$/);

export const EntryKind = z.enum([
  'deploy', 'setup', 'shock', 'mandate', 'action', 'rejection', 'killswitch', 'admin', 'other',
]);

export const ManifestSchema = z
  .object({
    name: z.string().min(1),
    chainId: z.number().int().positive(),
    vault: Address,
    explorerBase: z.string().default(''),
    note: z.string().default(''),
    entries: z.array(
      z.object({ label: z.string().min(1), kind: EntryKind, txHash: Hash, runId: z.string().optional() }).strict(),
    ),
    runs: z.array(
      z
        .object({
          runId: z.string(),
          scenario: z.string(),
          state: z.string(),
          driver: z.enum(['ui', 'api']),
          llmMode: z.enum(['scripted', 'live']),
          llmModels: z.array(z.string()),
          auditVerified: z.boolean(),
          mandateTx: Hash.nullable(),
          actionTxs: z.array(Hash),
          spentUsd8: z.string(),
        })
        .strict(),
    ),
  })
  .strict();
export type Manifest = z.infer<typeof ManifestSchema>;

export interface ReceiptRecord {
  label: string;
  kind: string;
  txHash: string;
  status: 'success' | 'reverted';
  blockNumber: string;
  gasUsed: string;
  from: string;
  to: string | null;
  actionExecutedEvents: number;
}

export interface ReceiptSet {
  generator: string;
  generatedAt: string;
  rpcHost: string;
  chainId: number;
  vault: string;
  vaultState: { paused: boolean; activeMandateId: string };
  receipts: ReceiptRecord[];
}

export function networkLabel(chainId: number): 'REAL SEPOLIA' | 'LOCAL ANVIL' | 'REAL TESTNET' {
  if (chainId === 11155111) return 'REAL SEPOLIA';
  if (chainId === 31337 || chainId === 31338) return 'LOCAL ANVIL';
  return 'REAL TESTNET';
}

/** Derive one manifest run record from the agent's own `/api/state` and `/api/audit` responses. */
export function runFromApi(
  state: unknown,
  audit: unknown,
  extra: { scenario: string; driver: 'ui' | 'api' },
): Manifest['runs'][number] {
  const s = z
    .object({
      runId: z.string(),
      runState: z.string(),
      mandateTxHash: Hash.nullable().optional(),
      ledger: z.array(z.object({ txHash: Hash.nullable().optional(), status: z.string() }).passthrough()),
      vault: z.object({ spentUsd8: z.union([z.string(), z.number()]) }).passthrough(),
    })
    .passthrough()
    .parse(state);
  const a = z
    .object({
      verified: z.boolean(),
      entries: z.array(z.object({ kind: z.string(), data: z.unknown() }).passthrough()),
    })
    .passthrough()
    .parse(audit);
  const models = new Set<string>();
  for (const entry of a.entries) {
    if (entry.kind !== 'llm.response') continue;
    const model = z.object({ model: z.string() }).safeParse(entry.data);
    if (model.success) models.add(model.data.model);
  }
  const llmModels = [...models];
  const live = llmModels.some((model) => !model.startsWith('scripted'));
  return {
    runId: s.runId,
    scenario: extra.scenario,
    state: s.runState,
    driver: extra.driver,
    llmMode: live ? 'live' : 'scripted',
    llmModels,
    auditVerified: a.verified,
    mandateTx: s.mandateTxHash ?? null,
    actionTxs: s.ledger.filter((row) => row.status === 'mined' && row.txHash).map((row) => row.txHash as string),
    spentUsd8: String(s.vault.spentUsd8),
  };
}

function usd(usd8: string): string {
  const value = BigInt(usd8);
  const cents = (value * 100n) / 100_000_000n;
  return `$${cents / 100n}.${(cents % 100n).toString().padStart(2, '0')}`;
}

function link(base: string, kind: 'tx' | 'address', value: string): string {
  const short = `${value.slice(0, 10)}…${value.slice(-6)}`;
  return /^https?:\/\//.test(base) ? `[\`${short}\`](${base.replace(/\/$/, '')}/${kind}/${value})` : `\`${short}\``;
}

/** Deterministic Markdown. Every hash in it is read back from a receipt, never typed. */
export function renderEvidence(sets: { manifest: Manifest; receipts: ReceiptSet }[]): string {
  const out: string[] = [
    '# Execution evidence (generated)',
    '',
    '> Generated by `pnpm --filter @marginpilot/agent evidence generate` from on-chain receipts. Do not edit by hand.',
    '> Every row below was read back from the chain at generation time. The lending market is a SIMULATED',
    '> contract (D-002); the transactions and the vault enforcement are real on the chain named in each section.',
    '',
  ];
  for (const { manifest, receipts } of sets) {
    const label = networkLabel(manifest.chainId);
    out.push(`## ${label} · chain ${manifest.chainId} · \`${manifest.name}\``, '');
    out.push(`- Vault: ${link(manifest.explorerBase, 'address', manifest.vault)} (full address \`${manifest.vault}\`)`);
    out.push(`- Generated: ${receipts.generatedAt} via ${receipts.rpcHost}`);
    out.push(`- Vault state at generation: paused=${receipts.vaultState.paused}, activeMandateId=${receipts.vaultState.activeMandateId}`);
    if (manifest.note) out.push(`- Note: ${manifest.note}`);
    out.push('', '| Label | Kind | Status | Block | Gas | ActionExecuted | Tx |', '|---|---|---|---|---|---|---|');
    for (const receipt of receipts.receipts) {
      out.push(
        `| ${receipt.label} | ${receipt.kind} | ${receipt.status} | ${BigInt(receipt.blockNumber)} | ${BigInt(receipt.gasUsed)} | ${receipt.actionExecutedEvents} | ${link(manifest.explorerBase, 'tx', receipt.txHash)} |`,
      );
    }
    out.push('');
    for (const run of manifest.runs) {
      out.push(
        `### Run \`${run.runId}\` · ${run.scenario}`,
        '',
        `- Driver: ${run.driver === 'ui' ? 'web console (browser)' : 'HTTP API'}; final state **${run.state}**; audit chain verified: ${run.auditVerified}`,
        `- LLM: **${run.llmMode === 'live' ? 'live model' : 'ScriptedLlm (no model call)'}**${run.llmModels.length ? ` (${run.llmModels.join(', ')})` : ''}`,
        `- Spent under the mandate: ${usd(run.spentUsd8)}`,
        `- Mandate tx: ${run.mandateTx ? link(manifest.explorerBase, 'tx', run.mandateTx) : 'n/a'}; mined actions: ${run.actionTxs.map((hash) => link(manifest.explorerBase, 'tx', hash)).join(', ') || 'none'}`,
        '',
      );
    }
  }
  out.push(
    '## Demo-only parts (read before relying on any number above)',
    '',
    '- **Simulated lending market.** `LendingSim`, `MockOracle`, `MockSwap` and the mock tokens are contracts we deployed. Prices and positions are set by us; no real DeFi position was rescued.',
    '- **Admin helpers.** The shock, stale-price, pool-pause and reset controls are owner-signed calls on those simulator contracts, available only when the server runs with demo controls on a test chain.',
    '- **Server-held demo owner key.** On the public demo the server signs the owner EIP-712 mandate with a dedicated test key, inside a limited envelope (D-048). A wallet-signed path exists; no MetaMask run is claimed.',
    '- **LLM per run.** Each run above states whether the default `ScriptedLlm` or a live model produced the tool calls. The model never computes money, prices or limits.',
    '- **Not mainnet.** Mainnet is out of bounds for this project.',
    '',
  );
  return `${out.join('\n')}\n`;
}
